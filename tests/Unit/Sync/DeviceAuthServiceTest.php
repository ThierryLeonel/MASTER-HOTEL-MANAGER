<?php

namespace Tests\Unit\Sync;

use App\Services\Sync\DeviceAuthService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

/**
 * Phase 9.7.2, revised in Phase 9.7.4 to match DeviceAuthService's
 * corrected shared-secret model — see that class's docblock for why the
 * original bcrypt-hash design from 9.7.2 was replaced before ever being
 * used against a real database: a one-way hash can be verified but never
 * retrieved again to present on an outgoing call, which bidirectional
 * sync genuinely needs.
 */
class DeviceAuthServiceTest extends TestCase
{
    use RefreshDatabase;

    private function service(): DeviceAuthService
    {
        return app(DeviceAuthService::class);
    }

    public function test_registering_a_device_returns_it_with_a_plaintext_secret(): void
    {
        $result = $this->service()->register('Cloud VPS', 'https://vps.example.com');

        $this->assertNotNull($result['device']->id);
        $this->assertSame('Cloud VPS', $result['device']->name);
        $this->assertSame('https://vps.example.com', $result['device']->endpoint_url);
        $this->assertTrue($result['device']->is_active);
        $this->assertNotEmpty($result['secret']);
        $this->assertNotEmpty($result['device']->device_key);
    }

    public function test_the_secret_is_encrypted_at_rest_not_plaintext(): void
    {
        $result = $this->service()->register('Cloud VPS');

        $rawColumnValue = $result['device']->getRawOriginal('shared_secret');

        // The raw database value must not equal the plaintext secret (it's
        // Laravel's `encrypted` cast ciphertext) — but the model's own
        // accessor must decrypt it back to the exact original value.
        $this->assertNotSame($result['secret'], $rawColumnValue);
        $this->assertSame($result['secret'], $result['device']->shared_secret);
    }

    public function test_shared_secret_is_hidden_from_array_and_json_serialization(): void
    {
        $result = $this->service()->register('Cloud VPS');

        $this->assertArrayNotHasKey('shared_secret', $result['device']->toArray());
    }

    public function test_authenticate_succeeds_with_the_correct_key_and_secret(): void
    {
        $result = $this->service()->register('Cloud VPS', 'https://vps.example.com');

        $authenticated = $this->service()->authenticate($result['device']->device_key, $result['secret']);

        $this->assertNotNull($authenticated);
        $this->assertTrue($authenticated->is($result['device']));
    }

    public function test_authenticate_fails_with_the_wrong_secret(): void
    {
        $result = $this->service()->register('Cloud VPS');

        $authenticated = $this->service()->authenticate($result['device']->device_key, 'not-the-real-secret');

        $this->assertNull($authenticated);
    }

    public function test_authenticate_fails_with_an_unknown_device_key(): void
    {
        $authenticated = $this->service()->authenticate('unknown-key', 'anything');

        $this->assertNull($authenticated);
    }

    public function test_authenticate_fails_once_the_device_is_revoked(): void
    {
        $result = $this->service()->register('Cloud VPS');
        $this->service()->revoke($result['device']);

        $authenticated = $this->service()->authenticate($result['device']->device_key, $result['secret']);

        $this->assertNull($authenticated);
    }

    public function test_a_successful_authentication_updates_last_seen_at(): void
    {
        $result = $this->service()->register('Cloud VPS');
        $this->assertNull($result['device']->last_seen_at);

        $this->service()->authenticate($result['device']->device_key, $result['secret']);

        $this->assertNotNull($result['device']->fresh()->last_seen_at);
    }

    public function test_importing_a_device_records_the_exact_given_key_and_secret(): void
    {
        $device = $this->service()->import('Local Server', 'given-device-key-123', 'given-secret-456');

        $this->assertSame('given-device-key-123', $device->device_key);
        $this->assertSame('given-secret-456', $device->shared_secret);

        // What was imported on this side must authenticate exactly as if
        // it had been generated by register() on the other side.
        $authenticated = $this->service()->authenticate('given-device-key-123', 'given-secret-456');
        $this->assertNotNull($authenticated);
    }

    public function test_credentials_for_returns_what_this_installation_presents_outbound(): void
    {
        $result = $this->service()->register('Cloud VPS', 'https://vps.example.com');

        $credentials = $this->service()->credentialsFor($result['device']->fresh());

        $this->assertSame($result['device']->device_key, $credentials['device_key']);
        $this->assertSame($result['secret'], $credentials['secret']);
    }

    public function test_credentials_for_throws_when_a_device_has_no_secret_on_file(): void
    {
        $device = \App\Models\SyncDevice::create([
            'name' => 'Broken Device', 'device_key' => 'no-secret-key', 'is_active' => true,
        ]);

        $this->expectException(\RuntimeException::class);

        $this->service()->credentialsFor($device);
    }
}
